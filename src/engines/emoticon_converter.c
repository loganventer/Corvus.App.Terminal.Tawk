const char *emoticon_to_emoji(const char *word) {
    if (!word || !word[0] || strlen(word) > 12) return NULL;
    for (size_t i = 0; i < sizeof(TABLE) / sizeof(TABLE[0]); i++) {
        if (strcmp(TABLE[i].text, word) == 0) return TABLE[i].emoji;
    }
    return NULL;
}
